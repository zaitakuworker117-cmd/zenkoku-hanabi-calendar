const container = document.getElementById("fireworks-list");

function displayFireworks(list) {

  if (!container) return;

  container.innerHTML = "";

  // 開催日の早い順に並べ替え
  const sortedList = [...list].sort(
    (a, b) => new Date(a.date) - new Date(b.date)
  );

  sortedList.forEach((firework) => {

    const card = document.createElement("div");

    card.className = "firework-card";

  // 元のfireworks配列での位置を取得
  const originalIndex = fireworks.indexOf(firework);

  card.innerHTML = `
    <h2>${firework.name}</h2>

    <p>📅 ${firework.date}</p>

    <p>📍 ${firework.prefecture} ${firework.location}</p>

    <p>🕐 ${firework.time}</p>

    <p>🎆 ${firework.fireworks}</p>

    <a
      href="detail.html?id=${originalIndex}"
      class="detail-button">
      詳細を見る →
    </a>
  `;

  container.appendChild(card);
});
}


// ================================
// 都道府県フィルター
// ================================

function filterFireworks() {

  const select =
    document.getElementById("prefecture-filter");

  if (!select) return;

  const prefecture = select.value;

  const filtered =
    prefecture === "すべて"
      ? fireworks
      : fireworks.filter(
          firework =>
            firework.prefecture === prefecture
        );

  displayFireworks(filtered);
}

