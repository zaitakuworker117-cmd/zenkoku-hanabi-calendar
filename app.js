const searchInput =
  document.getElementById("search-input");

if (searchInput) {

  searchInput.addEventListener("input", function () {

    const keyword =
      searchInput.value
        .trim()
        .toLowerCase();

    const filtered =
      fireworks.filter(firework => {

        return (
          firework.name
            .toLowerCase()
            .includes(keyword)
          ||
          firework.prefecture
            .toLowerCase()
            .includes(keyword)
          ||
          firework.location
            .toLowerCase()
            .includes(keyword)
        );

      });

    displayFireworks(filtered);

  });

}


// ================================
// 開催時期フィルター
// ================================

function filterByPeriod(type) {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  let filtered = fireworks;

  if (type === "today") {
    filtered = fireworks.filter(firework => {
      const date = new Date(firework.date);
      date.setHours(0, 0, 0, 0);
      return date.getTime() === today.getTime();
    });
  }

  if (type === "weekend") {
    const day = today.getDay();
    const saturday = new Date(today);
    saturday.setDate(
      today.getDate() + (6 - day)
    );

    saturday.setHours(0, 0, 0, 0);
    const sunday = new Date(saturday);
    sunday.setDate(
      saturday.getDate() + 1
    );
    filtered = fireworks.filter(firework => {
      const date = new Date(firework.date);
      date.setHours(0, 0, 0, 0);
      return date >= saturday && date <= sunday;
    });
  }

  if (type === "month") {
    filtered = fireworks.filter(firework => {
      const date = new Date(firework.date);
      return (
        date.getFullYear() === today.getFullYear()
        &&
        date.getMonth() === today.getMonth()
      );
    });
  }

  displayFireworks(filtered);
}

// ================================
// 開催日でフィルター
// ================================

function filterByDate(date) {

  const filtered = fireworks.filter(
    firework => firework.date === date
  );

  displayFireworks(filtered);
}
